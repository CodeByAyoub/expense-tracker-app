// Helper function to get unique categories
export const getUniqueCategories = (expenses: Expense[]): string[] => {
  return Array.from(new Set(expenses.map(e => e.category))).sort();
};

// Helper function to get unique subcategories
export const getUniqueSubcategories = (expenses: Expense[]): string[] => {
  return Array.from(new Set(expenses.map(e => e.subcategory))).sort();
};

// Helper function to get unique tags
export const getUniqueTags = (expenses: Expense[]): string[] => {
  const allTags = expenses.flatMap(e => e.tags);
  return Array.from(new Set(allTags)).sort();
};

// Helper function to get unique payment methods
export const getUniquePaymentMethods = (expenses: Expense[]): string[] => {
  return Array.from(new Set(expenses.map(e => e.paymentMethod))).sort();
};
